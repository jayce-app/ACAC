const mediaStem = (src: string) =>
  src
    .split('/')
    .pop()
    ?.replace(/\.[^.]+$/, '')
    .toLowerCase() ?? src.toLowerCase()

/** Drop deleted dump/curated paths and hide video posters as separate tiles. */
export function mergeProjectMedia(extra: ProjectMedia[] = []): ProjectMedia[] {
  const blocked = new Set(
    [
      'hero.jpg',
      'logo.jpg',
      'logo-mark.svg',
      'logo-wordmark.svg',
      'favicon.png',
      'job-clip.mp4',
      'job-clip-poster.jpg',
      'job-clip-steel-frame.mp4',
      'job-clip-steel-frame-poster.jpg',
      'img-3081.jpg',
      'img-3082.jpg',
      'img-3083.jpg',
      'img-3084.jpg',
      'img-3085.jpg',
    ].map((n) => n.toLowerCase()),
  )

  const seen = new Set<string>()
  const out: ProjectMedia[] = []

  for (const item of [...projectMedia, ...extra]) {
    if (item.type === 'video') continue
    const file = item.src.split('/').pop()?.toLowerCase() ?? ''
    if (blocked.has(file)) continue
    if (file.includes('poster')) continue
    const key = mediaStem(item.src)
    if (seen.has(key)) continue
    seen.add(key)
    out.push(item)
  }
  return out
}
